#!/usr/bin/env python3
"""Trace the DONE GOLL wordmark from the client's PNG into clean SVG.

The only master is a 1774x887 RGBA export: black serif type on a transparent
ground, the word "Done" stacked over "Goll". Fine for looking at, soft at a
512px app icon and useless if the mark has to change colour (ink on paper,
paper on a photograph, white in dark mode). This upsamples the alpha, cuts it
at 50%, walks every ink boundary with OpenCV (outer edges and counters),
simplifies with Douglas-Peucker at a sub-pixel tolerance and writes vector.

Out:
  assets/brand/wordmark.svg   the stacked mark, one <path> per letter, currentColor
  js/brand.js                 the same SVG as a string, for inline use

    python3 scripts/trace_logo.py

The letters are grouped by LINE first and by x-overlap second: D and G share
an x-range, so a left-to-right grouping (the KAYA script) would weld them.
"""
import pathlib
import sys

import cv2
import numpy as np
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "scripts" / "src" / "logo.png"
OUT_SVG = ROOT / "assets" / "brand" / "wordmark.svg"
OUT_JS = ROOT / "js" / "brand.js"

WORK_W = 3000      # working width of the trimmed mark; hairline serifs need resolution
EPSILON = 0.9      # Douglas-Peucker tolerance in working pixels (~0.3 units of the 1000 viewBox)
MIN_AREA = 300     # speckle


def load_alpha(path):
    im = Image.open(path).convert("RGBA")
    a = np.asarray(im)[..., 3]
    ys, xs = np.where(a > 8)
    pad = 4
    a = a[max(0, ys.min() - pad): ys.max() + pad + 1, max(0, xs.min() - pad): xs.max() + pad + 1]
    h, w = a.shape
    scale = WORK_W / w
    big = cv2.resize(a, (WORK_W, round(h * scale)), interpolation=cv2.INTER_CUBIC)
    return (big > 127).astype(np.uint8), scale


def letters_of(mask):
    """Connected blobs, grouped into letters: by line, then by overlapping x."""
    n, labels, stats, _ = cv2.connectedComponentsWithStats(mask, connectivity=8)
    blobs = [i for i in range(1, n) if stats[i, cv2.CC_STAT_AREA] >= MIN_AREA]
    if not blobs:
        sys.exit("no ink found")
    cy = {i: stats[i, cv2.CC_STAT_TOP] + stats[i, cv2.CC_STAT_HEIGHT] / 2 for i in blobs}
    mid = (min(cy.values()) + max(cy.values())) / 2
    lines = [[i for i in blobs if cy[i] < mid], [i for i in blobs if cy[i] >= mid]]
    groups = []
    for line in lines:
        line.sort(key=lambda i: stats[i, cv2.CC_STAT_LEFT])
        cur = [line[0]]
        for i in line[1:]:
            prev_right = max(stats[j, cv2.CC_STAT_LEFT] + stats[j, cv2.CC_STAT_WIDTH] for j in cur)
            if stats[i, cv2.CC_STAT_LEFT] < prev_right - 4:
                cur.append(i)
            else:
                groups.append(cur)
                cur = [i]
        groups.append(cur)
    return labels, groups


def ring_paths(sub_mask, ox, oy, scale):
    contours, _ = cv2.findContours(sub_mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    d = []
    for c in contours:
        if cv2.contourArea(c) < 20:
            continue
        # pixel-centre contour -> pixel-edge contour: shift by half a pixel outward is
        # below the tolerance; keep centres
        approx = cv2.approxPolyDP(c, EPSILON, True).reshape(-1, 2)
        if len(approx) < 3:
            continue
        pts = [((x + ox) * scale, (y + oy) * scale) for x, y in approx]
        seg = f"M{pts[0][0]:.1f} {pts[0][1]:.1f}" + "".join(f"L{x:.1f} {y:.1f}" for x, y in pts[1:]) + "Z"
        d.append(seg)
    return "".join(d)


def main():
    if not SRC.exists():
        sys.exit(f"missing {SRC}")
    mask, _ = load_alpha(SRC)
    labels, groups = letters_of(mask)
    ys, xs = np.where(mask > 0)
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    scale = 1000.0 / (x1 - x0)
    vh = round((y1 - y0) * scale, 1)
    names = list("DoneGoll")
    parts = []
    for k, g in enumerate(groups):
        sub = np.isin(labels, g).astype(np.uint8)
        d = ring_paths(sub, -x0, -y0, scale)
        name = names[k] if k < len(names) else f"g{k}"
        parts.append(f'<path data-l="{name}" d="{d}"/>')
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 {vh}" fill="currentColor" '
           f'fill-rule="evenodd" role="img" aria-label="Done Goll">{"".join(parts)}</svg>')
    OUT_SVG.parent.mkdir(parents=True, exist_ok=True)
    OUT_SVG.write_text(svg, encoding="utf-8")
    OUT_JS.parent.mkdir(parents=True, exist_ok=True)
    OUT_JS.write_text(
        "// Generated by scripts/trace_logo.py from the client's PNG. Do not edit by hand.\n"
        "// Stacked \"Done / Goll\", one path per letter, painted in currentColor.\n"
        f"export const WORDMARK_RATIO = {round(vh / 1000, 4)};\n"
        f"export const WORDMARK = `{svg}`;\n", encoding="utf-8")
    print(f"letters {len(groups)} ({''.join(names[:len(groups)])}) viewBox 1000x{vh}  svg {len(svg)/1024:.1f}KB")


if __name__ == "__main__":
    main()
